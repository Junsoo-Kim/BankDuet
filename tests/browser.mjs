import fs from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser=await chromium.launch({channel:'msedge',headless:true})
const base='http://127.0.0.1:'+ (process.env.DEMO_PORT || '18474')
const folder='docs/evidence'
const title='신혼집 자기자금 · 두 은행 공동 계획'
const issues=[]
let goal
const context=await browser.newContext({viewport:{width:1380,height:970}})
const other=await browser.newContext({viewport:{width:1380,height:970}})
const kb=await context.newPage(),b=await other.newPage()
for(const p of [kb,b]){p.on('pageerror',e=>issues.push(e.message));p.setDefaultTimeout(18000)}
const btn=(p,t)=>p.getByRole('button',{name:t,exact:true})
try {
 await Promise.all([kb.goto(base+'/kb/'),b.goto(base+'/b/')])
 await btn(kb,'목표 만들기').click()
 await kb.getByLabel('목표 이름').fill(title)
 await kb.getByRole('checkbox').check()
 await btn(kb,'저장').click()
 await kb.locator('.hero h2').filter({hasText:title}).waitFor()
 goal=await kb.getByLabel('조회할 목표').inputValue()
 await b.locator('option[value="'+goal+'"]').waitFor({state:'attached'})
 await b.getByLabel('조회할 목표').selectOption(goal)
 await btn(b,'변경값 자동 공유').click()
 await kb.locator('.metrics').getByText('1,000,000,000원',{exact:true}).waitFor()
 await kb.getByRole('button',{name:/^v\d+ 승인$/}).click()
 await b.getByRole('button',{name:/^v\d+ 승인$/}).click()
 await kb.locator('.hero p').filter({hasText:'확정'}).waitFor()
 await b.getByLabel('내 은행에 남길 사유').fill('준호 개인 일정')
 await btn(b,'지출 반영').click()
 await kb.locator('.metrics').getByText('10,000,000원',{exact:true}).waitFor()
 if((await kb.locator('main').innerText()).includes('준호 개인 일정'))throw Error('개인 사유 노출')
 await kb.evaluate(()=>window.scrollTo(0,0))
 await kb.screenshot({path:folder+'/kb-gap.png'})
 await b.locator('.row').filter({hasText:'준호 개인 일정'}).waitFor()
 await b.screenshot({path:folder+'/b-expense.png'})
 await kb.getByRole('link',{name:'계획 상담'}).click()
 await btn(kb,'월 한도 유지, 기간 연장 허용하면 언제 달성해?').click()
 await kb.locator('.answer').filter({hasText:'122회차'}).waitFor()
 await kb.screenshot({path:folder+'/chat.png'})
 await kb.getByRole('link',{name:'실행 로그'}).click()
 await btn(kb,'상세').first().click()
 await kb.getByText('실행 순서',{exact:true}).waitFor()
 await kb.screenshot({path:folder+'/trace.png'})
 await kb.getByRole('link',{name:'공동 목표'}).click()
 await kb.locator('.metrics').waitFor()
 await context.setOffline(true)
 await btn(b,'월 한도 유지 · 기간 연장 제안').click()
 await b.locator('.hero p').filter({hasText:'122개월'}).waitFor()
 await context.setOffline(false)
 await kb.locator('.hero p').filter({hasText:'122개월'}).waitFor({timeout:30000})
 for(const p of [kb,b])await p.getByRole('button',{name:/^v\d+ 승인$/}).click()
 await kb.locator('.hero p').filter({hasText:'확정'}).waitFor()
 await kb.setViewportSize({width:390,height:844})
 await kb.screenshot({path:folder+'/mobile.png'})
 if(await kb.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('모바일 가로 넘침')
 const docs=await context.newPage()
 await docs.goto(base+'/kb/api/docs')
 await docs.locator('.swagger-ui .opblock').first().waitFor()
 await docs.screenshot({path:folder+'/swagger.png'})
 await docs.close()
 if(issues.length)throw Error(issues.join('\n'))
 await fs.writeFile(folder+'/browser.json',JSON.stringify({goal,sse_update:true,offline_recovery:true,mobile_width:390,page_errors:issues},null,2))
 console.log('PASS two browser contexts / SSE / offline recovery / chat / trace / 390px')
} finally {
 if(goal)await context.request.delete(base+'/kb/api/plans/'+goal).catch(()=>{})
 await browser.close()
}
